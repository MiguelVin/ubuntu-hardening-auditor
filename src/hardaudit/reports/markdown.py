"""Markdown report: readable on GitHub, in a ticket or in a wiki."""

from __future__ import annotations

STATUS_ICON = {"pass": "✅ PASS", "fail": "❌ FAIL", "skip": "⏭️ SKIP", "error": "⚠️ ERROR"}


def _cell(text: str) -> str:
    """Escape characters that would break a Markdown table cell."""
    return text.replace("\\", "\\\\").replace("|", "\\|").replace("\n", " ")


def render_markdown(report: dict) -> str:
    score = "N/A" if report["score"] is None else f"{report['score']}/100"
    lines = [
        "# hardaudit report",
        "",
        f"- **Target:** `{report['target']}`",
        f"- **Generated:** {report['generated_at']}",
        f"- **Score:** {score} ({report['grade']})",
        f"- **Coverage:** {report['evaluated']}/{report['total']} checks evaluated",
        "",
        "| Status | ID | Check | Severity | Detail |",
        "|---|---|---|---|---|",
    ]
    for r in report["results"]:
        lines.append(
            f"| {STATUS_ICON[r['status']]} | {r['id']} | {_cell(r['title'])} "
            f"| {r['severity']} | {_cell(r['detail'])} |"
        )

    failures = [r for r in report["results"] if r["status"] == "fail"]
    if failures:
        lines += ["", "## How to fix"]
        for r in failures:
            lines += ["", f"### {r['id']}: {r['title']}", "", "```bash", *r["remediation"], "```"]
            if r["mitre"]:
                lines += ["", "MITRE ATT&CK: " + ", ".join(r["mitre"])]

    lines += ["", "---", f"Generated by hardaudit {report['version']}.", ""]
    return "\n".join(lines)
